import { test } from 'node:test'
import assert from 'node:assert/strict'
import { mkdirSync, mkdtempSync, readFileSync, rmSync } from 'node:fs'
import { spawnSync } from 'node:child_process'
import { resolve, join } from 'node:path'
import { pathToFileURL } from 'node:url'
import { actionSupport } from './actions/support.ts'
import { workflowWarnings } from './import/workflows.ts'

const requests = [
  ['actions/upload-artifact@v4', { name: 'build', path: 'dist' }, 'actions/upload-artifact is unsupported: this runner has no artifact upload backend'],
  ['actions/cache@v4', { key: 'dependencies', path: 'node_modules' }, 'actions/cache is unsupported: this runner has no dependency cache backend'],
  ['actions/setup-node@v6', { 'node-version': '24', cache: 'npm' }, 'actions/setup-node dependency caching is unsupported: remove the cache input to run without caching'],
  ['actions/setup-go@v5', { 'go-version': '1.24', cache: 'true' }, 'actions/setup-go dependency caching is unsupported: remove the cache input to run without caching'],
] as const

test('unsupported artifact/cache work returns errors through both the canonical and generated CLI contracts', async () => {
  mkdirSync('.tmp', { recursive: true })
  const work = mkdtempSync(resolve('.tmp/actions-contract-'))
  try {
    const target = join(work, 'src/api')
    const generated = spawnSync(process.execPath, ['scripts/generate-api-client.mjs', target], { encoding: 'utf8' })
    assert.equal(generated.status, 0, generated.stderr)
    const file = join(work, 'src/actions/support.ts')
    const expected = '// Generated by gild-site/scripts/generate-api-client.mjs. Edit the site source.\n' + readFileSync('lib/actions/support.ts', 'utf8')
    assert.equal(readFileSync(file, 'utf8'), expected, 'generator delivers the exact canonical source')
    const cli = await import(pathToFileURL(file).href)
    for (const contract of [actionSupport, cli.actionSupport]) {
      for (const [uses, inputs, error] of requests) {
        const result = contract(uses, inputs)
        assert.equal(result.error, error, uses + ' must fail, not report a successful no-op')
        assert.ok(result.warnings.every((warning: string) => !warning.includes('no-op')))
      }
      for (const action of ['actions/setup-node@v6', 'actions/setup-go@v5']) {
        for (const cache of [undefined, '', false, 'false']) {
          const values = cache === undefined ? {} : { cache }
          assert.equal(contract(action, values).error, undefined, action + ' remains usable without caching')
        }
      }
      assert.equal(contract('actions/checkout@v4', { 'fetch-depth': '0' }).error, undefined)
      assert.match(contract('unknown/action@v1', {}).error!, /doesn't run unknown\/action/)
    }
  } finally { rmSync(work, { recursive: true, force: true }) }
})

test('import diagnostics identify unsupported artifacts and caches without claiming no-op support', () => {
  const yaml = 'on: push\njobs:\n  test:\n    runs-on: self-hosted\n    steps:\n' + requests.map(([uses, inputs]) =>
    '      - uses: ' + uses + '\n        with:\n' + Object.entries(inputs).map(([key, value]) => '          ' + key + ': ' + JSON.stringify(value) + '\n').join(''),
  ).join('')
  const reports = workflowWarnings('ci.yml', yaml)
  for (const [, , error] of requests) assert.ok(reports.includes('ci.yml: ' + error), error)
  assert.ok(reports.every(report => !report.includes('no-op')))
  const disabled = workflowWarnings('ci.yml', 'on: push\njobs:\n  test:\n    runs-on: self-hosted\n    steps:\n      - uses: actions/setup-node@v6\n        with:\n          node-version: "24"\n          cache: false\n')
  assert.deepEqual(disabled, [])
})
