import { launchChrome } from './chrome.mjs'
import assert from 'node:assert/strict'
import { resolve } from 'node:path'
process.env.TMPDIR = resolve('.tmp')
const browser = await launchChrome()
const context = await browser.newContext({viewport:{width:1280,height:900}})
const page = await context.newPage(), errors=[]
page.on('pageerror',(e)=>errors.push(e.message))
try {
  await page.goto('http://localhost:8801/acme/demo',{waitUntil:'networkidle'})
  await page.getByRole('button',{name:'Search code',exact:true}).click()
  await page.getByRole('dialog',{name:'Search code',exact:true}).waitFor()
  await page.keyboard.press('Escape')
  await page.getByRole('dialog',{name:'Search code',exact:true}).waitFor({state:'hidden'})
  await page.keyboard.press('/')
  await page.getByRole('dialog',{name:'Search code',exact:true}).waitFor()
  assert.equal(await page.getByRole('combobox').evaluate(e=>document.activeElement===e),true)
  await page.getByRole('combobox').fill('sparse')
  await page.waitForFunction(()=>document.querySelectorAll('mark').length>0)
  await page.screenshot({path:'docs/repo-index/search-dark.png'})
  assert.equal(await page.evaluate(()=>document.body.style.overflow),'hidden')
  await page.keyboard.press('Escape'); await page.getByRole('dialog',{name:'Search code',exact:true}).waitFor({state:'hidden'})
  assert.equal(await page.evaluate(()=>document.body.style.overflow),'')
  await page.keyboard.press('t'); await page.getByRole('dialog',{name:'Go to file'}).waitFor()
  await page.getByRole('combobox').fill('srcidx')
  await page.waitForFunction(()=>document.querySelector('[role=option]')?.textContent.includes('src/index.ts'))
  await page.keyboard.press('Enter'); await page.waitForURL('**/acme/demo?ref=main&path=src%2Findex.ts#L1')
  await page.keyboard.press('/'); await page.getByRole('combobox').fill('sparse')
  await page.waitForFunction(()=>document.querySelectorAll('mark').length>0)
  await page.keyboard.press('Control+Enter'); await page.waitForURL('**/acme/demo/search?q=sparse')
  await page.getByText('1 file results',{exact:true}).waitFor()
  await page.screenshot({path:'docs/repo-index/search-results.png'})
  await page.goto('http://localhost:8801/acme/demo',{waitUntil:'networkidle'})
  await page.evaluate(()=>{ localStorage.setItem('gild.theme','light'); document.documentElement.dataset.theme='light' })
  await page.keyboard.press('/'); await page.getByRole('combobox').fill('sparse')
  await page.waitForFunction(()=>document.querySelectorAll('mark').length>0)
  await page.screenshot({path:'docs/repo-index/search-light.png'})
  await page.keyboard.press('ArrowDown'); assert.equal(await page.locator('[data-selected=true]').count(),1)
  await page.keyboard.press('Tab'); await page.keyboard.press('Tab'); await page.keyboard.press('Tab'); await page.keyboard.press('Tab')
  assert.equal(await page.getByRole('dialog',{name:'Search code',exact:true}).evaluate(e=>e.contains(document.activeElement)),true)
  await page.keyboard.press('Escape')
  await page.setViewportSize({width:400,height:844})
  await page.evaluate(()=>{ localStorage.setItem('gild.theme','dark'); document.documentElement.dataset.theme='dark' })
  await page.keyboard.press('/'); await page.getByRole('combobox').fill('sparse')
  await page.waitForFunction(()=>document.querySelectorAll('mark').length>0)
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=400),true,'no phone horizontal scroll')
  assert.equal(await page.getByRole('dialog',{name:'Search code',exact:true}).evaluate(e=>e.scrollWidth<=e.clientWidth),true,'no overlay horizontal scroll')
  await page.screenshot({path:'docs/repo-index/search-phone.png'})
  await page.getByRole('button',{name:'Remove repo:acme/demo scope'}).click()
  assert.equal(await page.locator('.search-scope').count(),0)
  await page.keyboard.press('Escape')
  await page.goto('http://localhost:8801/acme/demo/search?q=sparse')
  await page.getByText('1 file results',{exact:true}).waitFor()
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=400),true,'no results page horizontal scroll')
  await page.locator('.search-code-line').first().click(); await page.waitForURL('**#L2')
  assert.equal(await page.locator('#L2').evaluate(e=>e.matches(':target')),true)
  assert.deepEqual(errors,[])
  console.log('Headless Chrome: keyboard shortcuts, focus trap/restore, scope removal, fuzzy finder, full results, line anchors, both themes and 400px overflow checks passed.')
} finally { await browser.close() }
