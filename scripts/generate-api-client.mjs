// The site owns the contract. Publish these exact sources in the CLI PR;
// generation is deterministic and uses no fetched or handwritten route list.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { resolve, join } from 'node:path'
const target = resolve(process.argv[2] ?? '../gild-cli/src/api')
mkdirSync(target, { recursive: true })
for (const name of ['contract', 'scopes', 'client', 'bootstrap-contract', 'events-contract','sessions-contract','settings-contract','runner-contract','import-contract','orchestrator-contract','channel-contract','agent-package-contract','read-contract'])
  writeFileSync(
    join(target, `${name}.ts`),
    '// Generated by gild-site/scripts/generate-api-client.mjs. Edit the site source.\n' +
      readFileSync(`lib/api/${name}.ts`, 'utf8'),
  )

mkdirSync(resolve(target, "../import"), {recursive:true})
writeFileSync(resolve(target,"../import/source.ts"), '// Generated by gild-site/scripts/generate-api-client.mjs. Edit the site source.\n'+readFileSync("lib/import/source.ts","utf8"))
writeFileSync(resolve(target,'../public-address.ts'),'// Generated by gild-site/scripts/generate-api-client.mjs. Edit the site source.\n'+readFileSync('lib/public-address.ts','utf8'))
mkdirSync(resolve(target,'../actions'),{recursive:true})
writeFileSync(resolve(target,'../actions/support.ts'),'// Generated by gild-site/scripts/generate-api-client.mjs. Edit the site source.\n'+readFileSync('lib/actions/support.ts','utf8'))
